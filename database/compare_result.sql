-- 第三步：验证（两个结果应对齐）
-- --------------------------------------------------

SELECT s.supervisor_name AS 督导, COUNT(*) AS 门店数
FROM store_info s
WHERE s.del_flag = 0 AND s.supervisor_name IS NOT NULL
GROUP BY s.supervisor_name ORDER BY 门店数 DESC;

SELECT admin_name AS 督导, COUNT(*) AS 门店数
FROM supervisor_store_access WHERE del_flag = 0
GROUP BY admin_name ORDER BY 门店数 DESC;
